import assert from 'node:assert/strict';
import { firstHourStep, equipmentPreview, missionRewardSummary } from '../src/first-hour.js';
import { LEVELS } from '../src/config.js';
import { rollItemKey } from '../src/items.js';

const base = { classKey: 'vanguard', level: 1, items: [], equipment: {}, stats: {} };
const weapon = rollItemKey('scatter_mk1', 7, 1, 1);
assert.equal(firstHourStep(null), 'create');
assert.equal(firstHourStep(base), 'market');
assert.equal(firstHourStep({ ...base, items: [weapon] }), 'equip');
assert.equal(firstHourStep({ ...base, equipment: { weapon } }), 'forge');
const equipped = { ...base, equipment: { weapon } };
assert.equal(firstHourStep({ ...equipped, craftingMaterials: { alloy_shard: 3, phase_flux: 1 } }), 'forge', 'materials are inputs, not completed work');
assert.equal(firstHourStep({ ...equipped, craftingComponents: [{ id: 'component_1', componentId: 'frame_drive', location: 'inventory' }] }), 'forge', 'loose components are inputs, not completed work');
assert.equal(firstHourStep({ ...equipped, equipmentItemInstances: { weapon: { id: 'item_1', legacyKey: weapon, sockets: [{ color: 'frame', type: 'drive', component: null }] } } }), 'mission', 'a socketed owned item proves Forge work');
assert.equal(firstHourStep({ ...equipped, equipmentItemInstances: { weapon: { id: 'item_1', legacyKey: weapon, sockets: [{ color: 'frame', type: 'drive', component: { id: 'frame_drive', instanceId: 'component_1', rank: 1 } }] } } }), 'mission', 'an installed component proves Forge work');
assert.equal(firstHourStep({ ...base, stats: { victories: 1 } }), 'complete');
assert.equal(firstHourStep({ ...base, firstHourGuideDismissed: true }), 'complete');
assert.ok(equipmentPreview(base, weapon).target);
assert.match(missionRewardSummary(LEVELS[0]), /First Blood/);
console.log('first-hour checks passed');
