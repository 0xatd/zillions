import assert from 'node:assert/strict';
import { NavRouter, ROUTES } from '../src/nav/router.js';

const nav = new NavRouter();
assert.equal(nav.current().name, 'title');
nav.push('characters');
nav.push('home');
nav.push('overworld');
nav.push('setup');
assert.equal(nav.back().current, 'overworld', 'mission setup returns to the star system');
nav.openModal('confirm');
assert.equal(nav.back().current, 'overworld');
assert.equal(nav.snapshot().modal, null, 'back closes the one modal before leaving the screen');
nav.enterMatch();
assert.equal(ROUTES.pause.match, true);
assert.throws(() => nav.push('home'), /route_blocked_in_match/);
nav.push('pause');
nav.push('settings');
assert.equal(nav.back().current, 'pause');
assert.equal(nav.leaveMatch('home').inMatch, false);
console.log('shell state check passed');
