import test from 'node:test';
import assert from 'node:assert/strict';
import {newWorld,joinWorld,commandWorld,advanceWorld,ownedFleet,worldView,settleWorldBattle} from '../src/strategic-world.js';
const actor='a',character='c';
const joined=()=>joinWorld(newWorld(0),{actor,character,name:'Pilot'},0);
const cmd=(s,action,target,now=0)=>commandWorld(s,{actor,character,action,target,now});
test('continuous travel uses authority time, persists independently per player, and stops after disconnect lease',()=>{
 let s=joined();s=joinWorld(s,{actor:'b',character:'d',name:'Ally'},0);
 s=cmd(s,'move',{x:350,z:350}).state;
 s=advanceWorld(s,2500);assert.equal(ownedFleet(s,actor,character).x,255);assert.equal(ownedFleet(s,'b','d').x,160);
 s=cmd(s,'stop',null,2500).state;s=advanceWorld(s,10000);assert.equal(ownedFleet(s,actor,character).x,255);
 assert.throws(()=>cmd(s,'move',{x:Infinity,z:1},10000),/invalid_destination/);
 s=cmd(s,'move',{x:950,z:350},10000).state;s=advanceWorld(s,1000000);assert.equal(ownedFleet(s,actor,character).target,null);
 assert.equal(s.at,1000000);assert.equal(new Set(s.fleets.map(f=>f.id)).size,s.fleets.length);
});
test('arrival, ownership, progression and recruitment bounds are enforced',()=>{
 let s=joined();const r=cmd(s,'recruit');assert.equal(r.charge,12);assert.equal(ownedFleet(r.state,actor,character).troops,5);assert.equal(ownedFleet(s,actor,character).troops,4,'no input mutation');
 s=cmd(s,'move',{x:350,z:350}).state;assert.throws(()=>cmd(s,'recruit',null,1000),/arrival_required/);
 assert.throws(()=>commandWorld(s,{actor:'intruder',character,action:'stop',now:0}),/fleet_not_found/);
 s=joined();ownedFleet(s,actor,character).x=820;ownedFleet(s,actor,character).z=440;assert.throws(()=>cmd(s,'siege'),/campaign_locked/);
});
test('battle reservation blocks travel, retreat is pending-only, accepted outcome settles once',()=>{
 let s=cmd(joined(),'siege').state;const e=ownedFleet(s,actor,character).encounter;
 assert.throws(()=>cmd(s,'move',{x:2,z:2}),/encounter_pending/);
 s=cmd(s,'battle').state;s.encounters[0].status='battle';assert.throws(()=>cmd(s,'retreat'),/not_retreatable/);
 s=settleWorldBattle(s,{actor,character,encounter:e,won:true,troopsLost:2,now:500});assert.equal(ownedFleet(s,actor,character).troops,2);
 s=settleWorldBattle(s,{actor,character,encounter:e,won:true,troopsLost:2,now:500});assert.equal(ownedFleet(s,actor,character).troops,2);
 const view=worldView(s,actor,character);assert.equal(view.fleets.some(f=>'owner' in f||'character' in f||'seen' in f),false);
});
test('hostile encounter is generated by swept movement, not a client victory or collision claim',()=>{
 const s=joined(),f=ownedFleet(s,actor,character),enemy=s.fleets.find(f=>f.kind==='hostile');
 f.x=600;f.z=400;f.target={x:800,z:400};enemy.x=620;enemy.z=400;enemy.target={x:500,z:400};
 const next=advanceWorld(s,1000);assert.ok(ownedFleet(next,actor,character).encounter);
 assert.equal(next.encounters[0].kind,'fleet');assert.equal(next.encounters[0].status,'pending');
});

test('nearby party fleets join one encounter; settlement releases only each reporting army',()=>{
 let s=joined();s=joinWorld(s,{actor:'b',character:'d',name:'Ally'},0);s=cmd(s,'siege').state;const id=s.encounters[0].id;
 assert.throws(()=>commandWorld(s,{actor:'b',character:'d',action:'join',target:{encounter:id},now:0}),/party_required/);
 s=commandWorld(s,{actor:'b',character:'d',action:'join',target:{encounter:id},allies:['a'],now:0}).state;
 const room={id:'room-1',code:'ABCDEF',host:'a',level:1,mode:'campaign',members:['a','b']};
 s=commandWorld(s,{actor,character,action:'room',target:{actors:['a','b']},room,now:0}).state;
 assert.deepEqual(s.encounters[0].seats,['player:c','player:d']);s.encounters[0].status='battle';
 s=settleWorldBattle(s,{actor,character,encounter:id,won:true,troopsLost:1,now:1});
 assert.equal(ownedFleet(s,actor,character).encounter,null);assert.equal(ownedFleet(s,'b','d').encounter,id);
 s=settleWorldBattle(s,{actor:'b',character:'d',encounter:id,won:true,troopsLost:2,now:2});
 assert.equal(ownedFleet(s,'b','d').troops,2);assert.equal(s.encounters[0].status,'won');
});
test('abandoned battle can surrender and cannot charge the same army twice on a late report',()=>{
 let s=cmd(joined(),'siege').state;s.encounters[0].status='battle';const id=s.encounters[0].id;
 s=cmd(s,'surrender').state;assert.equal(ownedFleet(s,actor,character).troops,0);assert.equal(ownedFleet(s,actor,character).encounter,null);
 s=cmd(s,'recruit').state;s=settleWorldBattle(s,{actor,character,encounter:id,won:false,troopsLost:4,now:1});assert.equal(ownedFleet(s,actor,character).troops,1);
});
